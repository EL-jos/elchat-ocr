<?php

namespace App\Services\DevPilot;

/**
 * Retains a bounded beginning and rolling end of terminal output. The supplied
 * sanitizer runs before any bytes are discarded so secrets split across SSH
 * packets are reconstructed and redacted first.
 */
final class DevPilotCommandOutputBuffer
{
    public const TRUNCATION_MARKER = '[... sortie tronquée ...]';

    private readonly int $outputLimit;
    private readonly int $headLimit;
    private readonly int $tailLimit;
    private string $output = '';
    private string $head = '';
    private string $tail = '';
    private bool $truncated = false;

    public function __construct(int $outputLimit)
    {
        $this->outputLimit = max(1024, min(262144, $outputLimit));
        $available = $this->outputLimit - strlen(self::TRUNCATION_MARKER);
        $this->headLimit = intdiv($available, 4);
        $this->tailLimit = $available - $this->headLimit;
    }

    /** @param callable(string): string $sanitize */
    public function append(string $chunk, callable $sanitize): void
    {
        if ($this->truncated) {
            $this->tail = self::tailBytes($sanitize($this->tail.$chunk), $this->tailLimit);
            $this->output = $this->head.self::TRUNCATION_MARKER.$this->tail;
            return;
        }

        $candidate = $sanitize($this->output.$chunk);
        if (strlen($candidate) <= $this->outputLimit) {
            $this->output = $candidate;
            return;
        }

        // This marker is generated by this buffer. Remove any previous copy
        // before splitting so a second bounding pass still shows one marker.
        $candidate = str_replace(self::TRUNCATION_MARKER, '', $candidate);
        $this->head = mb_strcut($candidate, 0, $this->headLimit, 'UTF-8');
        $this->tail = self::tailBytes($candidate, $this->tailLimit);
        $this->truncated = true;
        $this->output = $this->head.self::TRUNCATION_MARKER.$this->tail;
    }

    public function output(): string
    {
        return $this->output;
    }

    public function isTruncated(): bool
    {
        return $this->truncated;
    }

    private static function tailBytes(string $value, int $byteLimit): string
    {
        if ($byteLimit <= 0 || $value === '') return '';

        $start = max(0, strlen($value) - $byteLimit);
        $length = strlen($value);
        while ($start < $length && (ord($value[$start]) & 0xC0) === 0x80) $start++;

        return substr($value, $start);
    }
}
